-- =========================================
-- ユーザーマスタ
-- =========================================
CREATE TABLE users (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    name_kana     VARCHAR(100),
    password_hash VARCHAR(255) NOT NULL,
    department    VARCHAR(100),
    is_admin      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    DATE,
    created_by    INTEGER REFERENCES users(user_id),
    updated_at    DATE,
    updated_by    INTEGER REFERENCES users(user_id)
);

-- =========================================
-- 商品マスタ
-- =========================================
CREATE TABLE products (
    product_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category     VARCHAR(50),
    product_name VARCHAR(100) NOT NULL,
    created_at   DATE,
    created_by   INTEGER REFERENCES users(user_id),
    updated_at   DATE,
    updated_by   INTEGER REFERENCES users(user_id)
);

-- =========================================
-- 在庫管理
-- =========================================
CREATE TABLE inventories (
    inventory_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     INTEGER NOT NULL UNIQUE REFERENCES products(product_id),
    stock_quantity INTEGER NOT NULL DEFAULT 0
                   CHECK (stock_quantity >= 0),
    notes          VARCHAR(500),
    created_at     DATE,
    created_by     INTEGER REFERENCES users(user_id),
    updated_at     DATE,
    updated_by     INTEGER REFERENCES users(user_id)
);

-- =========================================
-- 仕入先マスタ
-- =========================================
CREATE TABLE suppliers (
    supplier_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(100) NOT NULL,
    address       VARCHAR(255),
    phone         VARCHAR(30),
    notes         VARCHAR(500),
    created_at    DATE,
    created_by    INTEGER REFERENCES users(user_id),
    updated_at    DATE,
    updated_by    INTEGER REFERENCES users(user_id)
);

-- =========================================
-- 販売先マスタ
-- =========================================
CREATE TABLE customers (
    customer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    address       VARCHAR(255),
    phone         VARCHAR(30),
    notes         VARCHAR(500),
    created_at    DATE,
    created_by    INTEGER REFERENCES users(user_id),
    updated_at    DATE,
    updated_by    INTEGER REFERENCES users(user_id)
);

-- =========================================
-- 仕入履歴
-- =========================================
CREATE TABLE purchase_history (
    purchase_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id   INTEGER NOT NULL REFERENCES suppliers(supplier_id),
    product_id    INTEGER NOT NULL REFERENCES products(product_id),
    status        VARCHAR(20) NOT NULL DEFAULT 'new',
    purchase_quantity INTEGER NOT NULL CHECK (purchase_quantity > 0),
    notes         VARCHAR(500),
    created_at    DATE,
    created_by    INTEGER REFERENCES users(user_id),
    updated_at    DATE,
    updated_by    INTEGER REFERENCES users(user_id)
);

-- =========================================
-- 販売履歴
-- =========================================
CREATE TABLE sales_history (
    sales_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INTEGER NOT NULL REFERENCES customers(customer_id),
    product_id    INTEGER NOT NULL REFERENCES products(product_id),
    status        VARCHAR(20) NOT NULL DEFAULT 'new',
    sales_quantity INTEGER NOT NULL CHECK (sales_quantity > 0),
    notes         VARCHAR(500),
    created_at    DATE,
    created_by    INTEGER REFERENCES users(user_id),
    updated_at    DATE,
    updated_by    INTEGER REFERENCES users(user_id)
);